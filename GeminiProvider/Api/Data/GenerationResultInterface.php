declare(strict_types=1);

namespace Bgomesweb\GeminiProvider\Api\Data;

interface GenerationResultInterface
{
    public const KEY_TEXT = 'text';
    public const KEY_MODEL = 'model';
    public const KEY_TOKENS_INPUT = 'tokens_input';
    public const KEY_TOKENS_OUTPUT = 'tokens_output';
    public const KEY_STATUS = 'status';
    public const KEY_COST_USD = 'cost_usd';

    public const STATUS_SUCCESS = 'success';
    public const STATUS_BLOCKED = 'blocked';
    public const STATUS_TRUNCATED = 'truncated';

    /**
     * Sanitized HTML generated by the model.
     *
     * @return string
     */
    public function getText(): string;

    /**
     * Model that actually served the request (primary or fallback).
     *
     * @return string
     */
    public function getModel(): string;

    /**
     * @return int
     */
    public function getTokensInput(): int;

    /**
     * @return int
     */
    public function getTokensOutput(): int;

    /**
     * One of self::STATUS_* constants.
     *
     * @return string
     */
    public function getStatus(): string;

    /**
     * @return float
     */
    public function getCostUsd(): float;

    /**
     * Untyped on purpose: signature must match \Magento\Framework\DataObject::setData()
     * exactly (no param/return types) so implementors can inherit it without a PHP
     * "Declaration must be compatible" fatal error.
     *
     * @param  string|array $key
     * @param  mixed $value
     * @return $this
     */
    public function setData($key, $value = null);
}
